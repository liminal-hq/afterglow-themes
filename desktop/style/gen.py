#!/usr/bin/env python3
# Generate the sources of the original Afterglow visual style: bitmaps (drawn by agart.py) for each colour scheme, one Normal INI
# per scheme (from ini/normal.ini), themes.ini, the resource script and each scheme's registry file. Nothing is read from any other
# visual style.
# Usage: gen.py OUT_DIR [--preview PNG] [--scrollbars]   (OUT_DIR receives art/, textfiles/, schemes/ and afterglow.rc)
# By default the scroll bars are classic Windows ones (ini/scroll-classic.ini, classic images in scroll/); --scrollbars builds the
# Afterglow scroll bars instead (the drawing code and the INI sections are kept either way).
#
# (c) Copyright 2026 Liminal HQ, Scott Morris
# SPDX-License-Identifier: Apache-2.0 OR MIT
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)

import numpy as np  # noqa: E402

from agart import all_art  # noqa: E402
from agdraw import CTL, DUSK, P, encode_bmp, ini_colour, mix, rgb  # noqa: E402

# The colour schemes, in the order the engine lists them; the first is the default. Display names are string 1000 + n, tooltips
# 2000 + n (uxtheme EnumThemeColors).
COLOURS = [
	("Dusk", "Navy to rose dusk captions, a near-black taskbar and a gold Start button"),
	("Ember", "Aubergine to burnt orange and coral captions, a warm near-black taskbar and a pale gold Start button"),
	("Aurora", "Teal-navy to teal and violet captions, a blue-black taskbar and a mint Start button"),
	("Graphite", "Charcoal to slate and warm grey captions, a near-black taskbar and a gold Start button"),
	("Dusk Light", "Peach to lilac paper captions with dark titles, a cream and lavender taskbar and a gold Start button"),
	("Ember Light", "Apricot to coral paper captions with dark titles, a warm cream taskbar and a gold Start button"),
	("Aurora Light", "Mint to lavender paper captions with dark titles, a cool light taskbar and a mint Start button"),
	("Graphite Light", "Pale grey captions with dark titles, a light grey taskbar and a gold Start button"),
]


def slug(colour):
	"""Folder, file and resource stem for a scheme: "Dusk Light" gives "dusklight" (resource names) or "dusk-light" (files)."""
	return colour.lower().replace(" ", "")


def prefix(colour):
	"""Short folder for a scheme's own images in the style ("Ember" e/, "Dusk Light" dl/); short, since the INIs name them often."""
	return "".join(w[0] for w in colour.lower().split())


def file_stem(colour):
	return colour.lower().replace(" ", "-")


def luminance(c):
	c = np.asarray(c, dtype=float) / 255
	c = np.where(c <= 0.03928, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)
	return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def contrast(a, b):
	la, lb = sorted((luminance(a), luminance(b)), reverse=True)
	return (la + 0.05) / (lb + 0.05)


def check_contrast(colour):
	"""Title text against every ramp step with the caption's 5 % top glow (the worst case), and the inactive title: 4.5:1 or better."""
	steps = [mix(c, P["white"], 0.05) for c in DUSK] + list(DUSK)
	worst = min(contrast(P["title_text"], c) for c in steps)
	inactive = contrast(P["muted"], P["raised"])
	if worst < 4.5 or inactive < 4.5:
		sys.exit(f"{colour}: caption contrast {worst:.1f}:1, inactive {inactive:.1f}:1 (need 4.5:1)")
	return worst, inactive
SIZE_NAME = "Normal"
DOC = {
	"DisplayName": "Afterglow",
	"ToolTip": "Afterglow captions, a near-black taskbar and a bright Start button over classic cream controls, in four colour schemes",
	"Company": "Liminal HQ",
	"Author": "Liminal HQ, Scott Morris",
	"Copyright": "(c) Copyright 2026 Liminal HQ, Scott Morris. Apache-2.0 OR MIT",
	"URL": "",
	"Version": "1.1",
	"Description": "Original Afterglow visual style for ReactOS, drawn from the Liminal HQ Afterglow palette",
}
# The six title colours of HKCU\Control Panel\Colors that a scheme sets (the rest of the classic cream scheme stays).
TITLE_COLOURS = [
	("ActiveTitle", "dusk1"),
	("GradientActiveTitle", "dusk7"),
	("InactiveTitle", "raised"),
	("GradientInactiveTitle", "raised2"),
	("TitleText", "title_text"),
	("InactiveTitleText", "muted"),
]


def tokens():
	t = {k: ini_colour(v) for k, v in P.items()}
	for i, c in enumerate(DUSK):
		t[f"dusk{i + 1}"] = ini_colour(c)
	for i, c in enumerate(CTL):
		t[f"ctl{i + 1}"] = ini_colour(c)
	t["tab_edge"] = ini_colour(mix(CTL[0], P["edge"], 0.6))
	return t


def res_name(path):
	return re.sub(r"[\\/.]", "_", path).upper()


def ini_res(colour):
	return f"{slug(colour).upper()}_{SIZE_NAME.upper()}_INI"


def scheme_reg(colour, tok):
	lines = [
		"Windows Registry Editor Version 5.00",
		"",
		f'; Afterglow colour scheme "{colour}", generated by gen.py: selects it in the theme manager (the style itself is selected by',
		"; afterglow-original.reg) and sets the classic scheme's six title colours to match. Takes effect at the next logon; picking the",
		"; scheme in Display Properties, Appearance applies it at once.",
		";",
		"; (c) Copyright 2026 Liminal HQ, Scott Morris",
		"; SPDX-License-Identifier: Apache-2.0 OR MIT",
		"",
		"[HKEY_CURRENT_USER\\Software\\Microsoft\\Windows\\CurrentVersion\\ThemeManager]",
		f'"ColorName"="{colour}"',
		"",
		"[HKEY_CURRENT_USER\\Control Panel\\Colors]",
	]
	lines += [f'"{k}"="{tok[t]}"' for k, t in TITLE_COLOURS]
	return "\n".join(lines) + "\n"


def drop_sections(ini, stem):
	"""The INI text without every section whose name starts with stem (case-insensitive), such as "Scrollbar." for all of that class."""
	out, skipping = [], False
	for ln in ini.splitlines():
		if ln.startswith("["):
			skipping = ln[1:].lower().startswith(stem.lower())
		if not skipping:
			out.append(ln)
	return "\n".join(out)


def main():
	args = sys.argv[1:]
	out = args.pop(0)
	scrollbars = "--scrollbars" in args
	if scrollbars:
		args.remove("--scrollbars")
	preview = args[1] if len(args) > 1 and args[0] == "--preview" else None
	os.makedirs(os.path.join(out, "textfiles"), exist_ok=True)
	os.makedirs(os.path.join(out, "schemes"), exist_ok=True)
	src = open(os.path.join(here, "ini", "normal.ini"), encoding="utf-8").read()
	if not scrollbars:  # the classic scroll bars take the Afterglow ones' place
		src = drop_sections(src, "Scrollbar.") + "\n" + open(os.path.join(here, "ini", "scroll-classic.ini"), encoding="utf-8").read()
	# The shipped copy drops comments and blank lines and writes "Key=value" with LF line ends (the engine skips comments, trims
	# spaces around the "=" and treats CR as a space), which keeps eight INI resources small.
	# Number lists lose their spaces after commas too ("4,4,4,4"; the engine skips any non-digit between numbers).
	src = "\n".join(re.sub(r"^([^\[=]+?)\s*=\s*", r"\1=", ln.strip()) for ln in src.splitlines() if ln.strip() and not ln.lstrip().startswith(";"))
	src = re.sub(r"(?m)^([^=\n]+=)([-0-9, ]+)$", lambda m: m.group(1) + m.group(2).replace(", ", ","), src)
	image_re = re.compile(r"^(\s*(?:Glyph)?ImageFile\s*=\s*)(\S+)", re.M | re.I)

	# Every scheme draws the full set; an image whose bytes match one already kept is shared, otherwise it is kept under the
	# scheme's own folder ("ember/window/caption.bmp"). The engine maps an INI image name to a resource name, so each scheme's INI
	# simply names its own copies.
	images, arrays, by_bytes = {}, {}, {}
	ini_total = 0
	for n, (colour, _tip) in enumerate(COLOURS):
		art = all_art(colour, scrollbars)
		names = {}
		for path, a in art.items():
			data = encode_bmp(a)
			if data not in by_bytes:
				name = path if n == 0 else f"{prefix(colour)}/{path}"
				by_bytes[data] = name
				images[name] = data
				arrays[name] = a
			names[path] = by_bytes[data]
		tok = tokens()
		missing = sorted(set(re.findall(r"\{(\w+)\}", src)) - set(tok))
		if missing:
			sys.exit(f"unknown colour tokens: {missing}")
		ini = re.sub(r"\{(\w+)\}", lambda m: tok[m.group(1)], src)
		named = set(m.group(2) for m in image_re.finditer(ini))
		if named - set(art):
			sys.exit(f"INI names images that were not drawn: {sorted(named - set(art))}")
		if set(art) - named:
			sys.exit(f"images drawn but not used: {sorted(set(art) - named)}")
		ini = image_re.sub(lambda m: m.group(1) + names[m.group(2)], ini)
		body = "\n" + ini + "\n"
		ini_total += len(body) * 2
		with open(os.path.join(out, "textfiles", f"{file_stem(colour)}-normal.ini"), "w", encoding="utf-16-le", newline="") as f:
			f.write(body)
		with open(os.path.join(out, "schemes", f"{file_stem(colour)}.reg"), "w", encoding="ascii", newline="\n") as f:
			f.write(scheme_reg(colour, tok))
		own = sum(1 for v in names.values() if v.startswith(prefix(colour) + "/")) if n else len(set(names.values()))
		worst, inactive = check_contrast(colour)
		print(f"{colour}: {own} own bitmaps, {len(art) - own} shared; title {worst:.1f}:1 at worst, inactive {inactive:.1f}:1")
		if n == 0:  # afterglow-original.reg carries the default scheme's title colours; keep the two in step
			reg = open(os.path.join(here, "..", "install", "afterglow-original.reg"), encoding="ascii").read()
			for k, t in TITLE_COLOURS:
				if f'"{k}"="{tok[t]}"' not in reg:
					sys.exit(f"afterglow-original.reg: {k} is not {tok[t]} (the {colour} scheme)")
	total = 0
	for path, data in images.items():
		p = os.path.join(out, "art", path)
		os.makedirs(os.path.dirname(p), exist_ok=True)
		total += len(data)
		with open(p, "wb") as f:
			f.write(data)
	themes = "\r\n[Documentation]\r\n" + "".join(f"{k} = {v}\r\n" for k, v in DOC.items())
	with open(os.path.join(out, "textfiles", "themes.ini"), "w", encoding="utf-16-le", newline="") as f:
		f.write(themes)

	def s(v):
		return v.replace('"', '""')

	names0 = "".join(f"{c}\\0" for c, _ in COLOURS)
	inis = "".join(f"{ini_res(c)}\\0" for c, _ in COLOURS)  # colour n, size 0: entry n (index = sizes * colour + size)
	rc = [
		"// Generated by gen.py. (c) Copyright 2026 Liminal HQ, Scott Morris. SPDX-License-Identifier: Apache-2.0 OR MIT",
		"LANGUAGE 0, 0",
		"1 PACKTHEM_VERSION { 0x0003 }",
		f'1 COLORNAMES {{ L"{names0}\\0" }}',
		f'1 SIZENAMES {{ L"{SIZE_NAME}\\0\\0" }}',
		f'1 FILERESNAMES {{ L"{inis}\\0" }}',
		'THEMES_INI TEXTFILE "textfiles/themes.ini"',
	]
	rc += [f'{ini_res(c)} TEXTFILE "textfiles/{file_stem(c)}-normal.ini"' for c, _ in COLOURS]
	rc += [f'{res_name(p)} BITMAP "art/{p}"' for p in sorted(images)]
	keys = list(DOC)
	rc += [
		"STRINGTABLE {\n" + "\n".join(f' {1000 + i}, "{c}"' for i, (c, _) in enumerate(COLOURS)) + "\n}",
		"STRINGTABLE {\n" + "\n".join(f' {2000 + i}, "{s(t)}"' for i, (_, t) in enumerate(COLOURS)) + "\n}",
		f'STRINGTABLE {{ 3000, "{SIZE_NAME}" }}',
		f'STRINGTABLE {{ 4000, "{SIZE_NAME}" }}',
		"STRINGTABLE {\n" + "\n".join(f' {5000 + i}, "{s(DOC[k])}"' for i, k in enumerate(keys) if DOC[k]) + "\n}",
		"1 VERSIONINFO",
		"FILEVERSION 1,1,0,0",
		"PRODUCTVERSION 1,1,0,0",
		"FILEOS 0x40004",
		"FILETYPE 2",
		"{",
		' BLOCK "StringFileInfo" { BLOCK "040904b0" { VALUE "FileDescription", "Afterglow visual style\\0" VALUE "CompanyName", "Liminal HQ\\0" VALUE "LegalCopyright", "(c) 2026 Liminal HQ, Scott Morris. Apache-2.0 OR MIT\\0" VALUE "OriginalFilename", "afterglow.msstyles\\0" VALUE "FileVersion", "1.1\\0" } }',
		' BLOCK "VarFileInfo" { VALUE "Translation", 0x0409, 0x04b0 }',
		"}",
	]
	with open(os.path.join(out, "afterglow.rc"), "w", encoding="utf-8") as f:
		f.write("\n".join(rc) + "\n")
	print(f"{len(images)} bitmaps, {total} bytes of BMP; {len(COLOURS)} INIs, {ini_total} bytes")

	if preview:  # contact sheet of every bitmap at 3x, key colour shown as a check pattern
		from PIL import Image

		tiles = []
		for path, a in arrays.items():
			a = np.clip(np.round(a), 0, 255).astype(np.uint8)
			k = np.all(a == [255, 0, 255], axis=2)
			yy, xx = np.indices(k.shape)
			a[k] = np.where((((yy // 2) + (xx // 2)) % 2 == 0)[k, None], [70, 70, 80], [50, 50, 58])
			tiles.append(Image.fromarray(a).resize((a.shape[1] * 3, a.shape[0] * 3), Image.NEAREST))
		W = 1400
		x = y = rowh = 0
		pos = []
		for t in tiles:
			if x + t.width > W:
				x, y, rowh = 0, y + rowh + 8, 0
			pos.append((x, y))
			x += t.width + 8
			rowh = max(rowh, t.height)
		sheet = Image.new("RGB", (W, y + rowh), (128, 128, 128))
		for t, p in zip(tiles, pos):
			sheet.paste(t, p)
		sheet.save(preview)


if __name__ == "__main__":
	main()
